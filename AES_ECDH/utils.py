def derive_aes_key(shared_point, key_length_chars=32):
    """
    Dérive une clé hexadécimale AES à partir du point partagé ECDH.
    key_length_chars : 32, 48 ou 64 (nombre de caractères hexadécimaux)
    """
    if shared_point.is_inf():
        raise ValueError("Point partagé invalide")
    
    x_hex = format(shared_point.x, '02x')   # 2 caractères hex
    y_hex = format(shared_point.y, '02x')   # 2 caractères hex
    seed = x_hex + y_hex                    # 4 caractères hex
    
    # Combien de fois répéter le seed pour approcher la longueur voulue
    repeats = (key_length_chars + 3) // 4   # arrondi supérieur
    key = (seed * repeats)[:key_length_chars]
    
    return key.lower()


