def gf_mul(a: int, b: int, poly: int) -> int:
    """
    Multiply two bytes in GF(2^8) with your polynomial
    """
    result = 0
    for i in range(8):
        if b & 1:
            result ^= a
        hi_bit_set = a & 0x80
        a <<= 1
        if hi_bit_set:
            a ^= poly
        a &= 0xFF
        b >>= 1
    return result

