def g_function(word: bytes, round_number: int):
    rot_w = rotword(word)
    sub_word = bytes([
        s_box[rot_w[0]],
        s_box[rot_w[1]],
        s_box[rot_w[2]],
        s_box[rot_w[3]]
    ])

    round_word = bytes([round_constants[round_number], 0, 0, 0])
    return xor_bytes(round_word, sub_word)

def key_expansion_layer(key_str: str) -> list[bytes]:
    """
    Génère la clé étendue AES à partir d'une clé hexadécimale
    Retourne une liste de mots (4 octets chacun)
    Supporte AES-128, AES-192 et AES-256
    """
    key = parse_hex_key(key_str)
    round_words = []

    # nombre total de mots selon la taille de la clé
    round_words_number_map = {
        16: 44,  # AES-128
        24: 52,  # AES-192
        32: 60   # AES-256
    }

    if len(key) not in round_words_number_map:
        raise Exception("Key must be 32, 48, or 64 hex characters")

    Nk = len(key) // 4  # nombre de mots dans la clé originale
    total_words = round_words_number_map[len(key)]

    initial_words = split_array(key, 4)
    round_words.extend(initial_words)
    
    for i in range(Nk, total_words):
        temp = round_words[-1]
        if i % Nk == 0:
            # Appliquer g_function pour les multiples de Nk
            temp = g_function(temp, i // Nk - 1)
        elif Nk == 8 and i % Nk == 4:
            # Pour AES-256, appliquer SubWord seulement (sans rotation)
            temp = bytes([s_box[b] for b in temp])
        # XOR avec le mot Nk positions en arrière
        round_words.append(xor_bytes(temp, round_words[i - Nk]))

    return round_words



def string_to_aes_blocks(text: str, block_size: int = 16):
    """
    Converts a string to 16-byte blocks (AES block size),
    padding with PKCS#7 if necessary.
    Returns a list of bytes objects.
    """
    # Convert string to bytes
    data = text.encode('utf-8')
    
    # Compute padding length
    pad_len = block_size - (len(data) % block_size)
    padding = bytes([pad_len] * pad_len)
    
    # Add padding
    data += padding
    
    # Split into 16-byte blocks
    blocks = [data[i:i+block_size] for i in range(0, len(data), block_size)]
    return blocks


def get_round_key(words_list: list[bytes], round_number: int, block_words: int = 4) -> bytes:
    """
    Constructs the AES round key for the given round number.
    
    :param words_list: list of 4-byte words (bytes objects)
    :param round_number: round number (0-based)
    :param block_words: number of words per block (always 4 for AES)
    :return: round key as bytes (16 bytes)
    """
    start = round_number * block_words
    end = start + block_words
    round_words = words_list[start:end]
    
    if len(round_words) != block_words:
        raise ValueError("Invalid round number or insufficient words in key schedule")
    
    # Concatenate words into a single 16-byte round key
    return b''.join(round_words)

