def poly_to_int(coeffs):
    return sum((c & 1) << i for i, c in enumerate(coeffs))

def split_array(data, size):
    return [data[i:i+size] for i in range(0, len(data), size)]

def rotword(word: bytes) -> bytes:
    return word[1:] + word[:1]

def parse_hex_key(key_str: str) -> bytes:
    if len(key_str) not in {32, 48, 64}:
        raise ValueError("Key must be 32, 48, or 64 hex characters")
    return bytes.fromhex(key_str)

def xor_bytes(bytes_a: bytes, bytes_b: bytes):
    return bytes(a ^ b for a, b in zip(bytes_a, bytes_b))

def calculate_round_constant(poly_generateur: list[int]):
    round_constants = [1]

    poly_int = poly_to_int(poly_generateur)
    reduction = poly_int & 0xFF

    for i in range(2, 15):
        prev = round_constants[i - 2]

        if prev < 0x80:
            constant = (prev << 1) & 0xFF
        else:
            constant = ((prev << 1) & 0xFF) ^ reduction

        round_constants.append(constant)

    return bytes(round_constants)


